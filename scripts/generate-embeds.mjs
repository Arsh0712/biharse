#!/usr/bin/env node
/**
 * Generate the embedded runtime seed (scripts/generate-embeds.mjs).
 *
 * Produces TypeScript modules under src/lib/seed/ that are compiled INTO the
 * serverless bundle as code — so a deployment works even if every database
 * and upload file was stripped by upload rules / gitignore:
 *
 *   src/lib/seed/seed-sql.ts     — full schema + data of db/custom.db as SQL
 *   src/lib/seed/seed-images.ts  — db/uploads/** as base64 data
 *
 * src/lib/db.ts materializes them at cold start ONLY when the bundled files
 * are missing AND the runtime database is empty (never overwrites real data).
 *
 * Usage: node scripts/generate-embeds.mjs   (run from the project root)
 */
import { Database } from 'bun:sqlite';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, relative, posix, sep } from 'node:path';

const root = process.cwd();
const dbPath = join(root, 'db', 'custom.db');
const uploadsDir = join(root, 'db', 'uploads');
const outDir = join(root, 'src', 'lib', 'seed');

if (!statSync(dbPath).isFile()) {
  console.error(`✖ generate-embeds: missing ${dbPath}`);
  process.exit(1);
}

const sqlite = new Database(dbPath, { readonly: true });

/* ── 1. SQL dump (dependency order = sqlite_master order, which Prisma keeps FK-safe) ── */
const esc = (v) => {
  if (v === null || v === undefined) return 'NULL';
  const t = typeof v;
  if (t === 'number') return String(v);
  if (t === 'bigint') return String(v);
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString('hex')}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const objects = sqlite
  .query("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_prisma_migrations' ORDER BY rowid")
  .all();

const parts = ['-- BiharSe embedded runtime seed — generated by scripts/generate-embeds.mjs'];
for (const o of objects) if (o.type === 'table') parts.push(`${o.sql};`);
for (const o of objects) if (o.type === 'index') parts.push(`${o.sql};`);

for (const o of objects) {
  if (o.type !== 'table') continue;
  const rows = sqlite.query(`SELECT * FROM "${o.name}"`).all();
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  const colList = cols.map((c) => `"${c}"`).join(', ');
  for (const row of rows) {
    const vals = cols.map((c) => esc(row[c])).join(', ');
    parts.push(`INSERT INTO "${o.name}" (${colList}) VALUES (${vals});`);
  }
}
sqlite.close();

const sql = parts.join('\n');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'seed-sql.ts'), `// AUTO-GENERATED by scripts/generate-embeds.mjs — do not edit.\n// Runtime fallback seed: used only when the bundled database files are missing.\nexport const SEED_SQL: string = ${JSON.stringify(sql)};\n`);
console.log(`✔ seed-sql.ts (${(sql.length / 1024).toFixed(0)} KB of SQL, ${objects.filter((o) => o.type === 'table').length} tables)`);

/* ── 2. Uploads as base64 ── */
function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const images = {};
if (statSync(uploadsDir).isDirectory()) {
  for (const file of walk(uploadsDir)) {
    const rel = relative(uploadsDir, file).split(sep).join(posix.sep);
    images[rel] = readFileSync(file).toString('base64');
  }
}
const total = Object.values(images).reduce((n, b) => n + b.length, 0);
writeFileSync(
  join(outDir, 'seed-images.ts'),
  `// AUTO-GENERATED by scripts/generate-embeds.mjs — do not edit.\n// Runtime fallback media: written to /tmp when bundled uploads are missing.\nexport const SEED_IMAGES: Record<string, string> = ${JSON.stringify(images, null, 0)};\n`,
);
console.log(`✔ seed-images.ts (${Object.keys(images).length} files, ${(total / 1024 / 1024).toFixed(2)} MB base64)`);
